// Turns the 26 example bills from my first project into SQL.
// Run it once with:  node scripts/make-bills-seed.mjs
// The bills are public facts. The summaries are my own wording from that project.
import { readFileSync, writeFileSync } from "node:fs";
import vm from "node:vm";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const source = join(here, "..", "..", "01-policy-navigator-ux-teardown", "prototype", "data.js");

const sandbox = { window: {} };
vm.runInNewContext(readFileSync(source, "utf8"), sandbox);
const data = sandbox.window.NAV_DATA;

const q = (s) => "'" + String(s).replace(/'/g, "''") + "'";
const rows = data.bills.map((b) => {
  const topics = b.dims.map((d) => data.dimensions[d]);
  const arr = topics.length ? "array[" + topics.map(q).join(", ") + "]::text[]" : "'{}'::text[]";
  return `  (${q(b.state)}, ${q(b.id)}, ${b.year}, ${q(b.status)}, ${q(b.text)}, ${arr})`;
});

const sql = `-- Generated by scripts/make-bills-seed.mjs from the first project's sample data.
-- ${rows.length} public example bills. Statuses are as shown on the original tool on 25 Nov 2026.
insert into public.bills (state, number, year, status, summary, topics) values
${rows.join(",\n")};
`;
writeFileSync(join(here, "..", "db", "05_bills.sql"), sql);
console.log("Wrote", rows.length, "bills");
